-- 2. Bandeja de solicitudes del formulario público
CREATE TABLE IF NOT EXISTS solicitudes (
  id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cedula         TEXT NOT NULL,
  datos          JSONB NOT NULL,
  estado         TEXT NOT NULL DEFAULT 'pendiente',   -- pendiente | aprobada | rechazada
  colaborador_id BIGINT,
  creado_en      TIMESTAMPTZ DEFAULT NOW(),
  revisado_en    TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS solicitudes_estado_idx ON solicitudes (estado);

-- 3. Desactivar temporalmente la marca automática mientras se ajustan los datos existentes
