-- 4. Pasar las labores al catálogo oficial del CEMP
--    Vigilancia → Logística (Vigilancia) · Llaves → Llaves de la iglesia · Cámaras → Video
--    Apoyo Ofrenda → Ofrenda (Grupo 1 - Recolector)
--    Ofrenda Interno / Ofrenda Organización → Ofrenda (Grupo 2)
--    La distinción Interno / Organización se conserva en observaciones.
UPDATE colaboradores
SET observaciones = TRIM(BOTH '; ' FROM CONCAT_WS('; ', NULLIF(observaciones, ''),
      CASE WHEN labores @> '["Ofrenda Interno"]'::jsonb      THEN 'Ofrenda: Interno' END,
      CASE WHEN labores @> '["Ofrenda Organización"]'::jsonb THEN 'Ofrenda: Organización' END))
WHERE (labores @> '["Ofrenda Interno"]'::jsonb OR labores @> '["Ofrenda Organización"]'::jsonb)
  AND COALESCE(observaciones, '') NOT LIKE '%Ofrenda: %';

UPDATE colaboradores c
SET labores = sub.nuevas
FROM (
  SELECT id, COALESCE(jsonb_agg(DISTINCT m.labor), '[]'::jsonb) AS nuevas
  FROM colaboradores,
  LATERAL (
    SELECT CASE e
      WHEN 'Vigilancia'           THEN 'Logística (Vigilancia)'
      WHEN 'Llaves'               THEN 'Llaves de la iglesia'
      WHEN 'Cámaras'              THEN 'Video'
      WHEN 'Apoyo Ofrenda'        THEN 'Ofrenda (Grupo 1 - Recolector)'
      WHEN 'Ofrenda Interno'      THEN 'Ofrenda (Grupo 2)'
      WHEN 'Ofrenda Organización' THEN 'Ofrenda (Grupo 2)'
      ELSE e END AS labor
    FROM jsonb_array_elements_text(COALESCE(labores, '[]'::jsonb)) AS e
  ) m
  GROUP BY id
) sub
WHERE c.id = sub.id;

-- 5. Separar el nombre completo en nombres y apellidos cuando aún no existan
--    (aproximado: 2 palabras = nombre + apellido; 3 = nombre + 2 apellidos; 4+ = 2 nombres + 2 apellidos)
UPDATE colaboradores SET
  primer_nombre    = split_part(n, ' ', 1),
  segundo_nombre   = CASE WHEN cnt >= 4 THEN split_part(n, ' ', 2) END,
  primer_apellido  = CASE WHEN cnt = 2 THEN split_part(n, ' ', 2)
                          WHEN cnt = 3 THEN split_part(n, ' ', 2)
                          ELSE split_part(n, ' ', 3) END,
  segundo_apellido = CASE WHEN cnt = 3 THEN split_part(n, ' ', 3)
                          WHEN cnt >= 4 THEN split_part(n, ' ', 4) END
FROM (
  SELECT id AS cid, regexp_replace(trim(nombre), '\s+', ' ', 'g') AS n,
         array_length(regexp_split_to_array(trim(nombre), '\s+'), 1) AS cnt
  FROM colaboradores
) x
WHERE colaboradores.id = x.cid AND colaboradores.primer_nombre IS NULL AND x.cnt >= 2;

-- 6. Quienes ya tienen roles en MIRA / FIMLM quedan marcados como voluntarios
UPDATE colaboradores SET es_mira  = TRUE WHERE es_mira  IS NULL AND jsonb_array_length(COALESCE(mira,  '[]'::jsonb)) > 0;
UPDATE colaboradores SET es_fimlm = TRUE WHERE es_fimlm IS NULL AND jsonb_array_length(COALESCE(fimlm, '[]'::jsonb)) > 0;

